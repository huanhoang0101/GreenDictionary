const express=require("express");
const cors=require("cors");
const app=express();
const PORT=process.env.PORT||3000;
app.use(cors());
app.use(express.json());
app.use("/api/dictionary",require("./routes/dictionary"));
app.use("/api/dictionary",require("./routes/random"));
app.use("/api/dictionary",require("./routes/detail"));
app.use("/api/examples",require("./routes/examples"));
app.use("/api/meanings",require("./routes/meanings"));
app.use("/api/grammar",require("./routes/grammar"));
app.get("/",require("./routes/home"));
app.listen(PORT,"0.0.0.0",()=>console.log(`API đang chạy tại http://localhost:${PORT}`));
